local Island = dofile('lib/island.luau')
local function track(changes)
    local t={musicEligible=true,player='test',trackId='a',title='Song',artist='Artist',playing=true,line='First line'}
    for k,v in pairs(changes or {}) do t[k]=v end
    return t
end
local m=Island.new({},0)
assert(Island.content(m,0,'12:34').mode=='clock')
Island.observe(m,track(),100)
assert(Island.content(m,100,'12:34').text=='First line')
Island.observe(m,track({playing=false}),1000)
Island.observe(m,track({playing=false,line=''}),2000)
assert(Island.content(m,300999,'12:34').text=='First line','Pause preserves the last lyric for five minutes')
assert(Island.content(m,301000,'12:34').mode=='clock','Pause expires at exactly five minutes')
Island.observe(m,track(),301100)
assert(Island.content(m,301100,'12:34').mode=='music','Resume restores music')
Island.observe(m,{},301101)
assert(Island.content(m,301101,'12:34').mode=='clock','No source returns clock immediately')
Island.observe(m,track({trackId='b',line='',playing=false}),301200)
assert(Island.content(m,301200,'12:34').text=='Song · Artist','New paused song must not inherit old lyrics')
Island.observe(m,track({trackId='b',line='♪'}),301250)
assert(Island.content(m,301250,'12:34').text=='Song · Artist','Instrumental gap uses metadata')
local a=Island.animation(72)
Island.target(a,{mode='music',text='One'},340)
Island.tick(a,100)
local width,alpha=Island.frame(a)
assert(width>72 and width<340 and alpha>=0 and alpha<=1)
Island.target(a,{mode='music',text='One'},340)
Island.tick(a,500)
assert(a.active,'Opening remains animated past the old 560ms duration')
Island.tick(a,1000)
Island.tick(a,600)
assert(not a.active,'Identical observations must not restart animation')
local expanding=Island.animation(72)
Island.target(expanding,{mode='music',text='First'},340)
Island.tick(expanding,1000)
local expansionWidth=Island.frame(expanding)
Island.target(expanding,{mode='music',text='Second'},340)
assert(Island.frame(expanding)==expansionWidth and expanding.elapsed==1000,
    'A lyric change must not restart or interrupt the slow opening')
Island.tick(expanding,1000);Island.tick(expanding,200)
assert(not expanding.active and expanding.width==340,'Opening finishes at2200ms despite incoming lyrics')
Island.target(a,{mode='clock',text='12:34'},72)
Island.tick(a,80)
local before=Island.frame(a)
local _,alphaBefore,shownBefore=Island.frame(a)
Island.target(a,{mode='music',text='Two'},340)
local after=Island.frame(a)
assert(math.abs(before-after)<0.001,'Interrupted transition keeps width continuous')
local _,alphaAfter,shownAfter=Island.frame(a)
assert(math.abs(alphaBefore-alphaAfter)<0.001 and shownBefore.text==shownAfter.text,
    'Interrupted transition keeps opacity and displayed content continuous')
Island.tick(a,1000)
Island.tick(a,1000)
Island.tick(a,200)
local w,opacity,shown=Island.frame(a)
assert(w==340 and opacity==1 and shown.text=='Two' and not a.active)
print('Island: pause timeout, source loss, fallback, resume and interrupted transitions passed')
